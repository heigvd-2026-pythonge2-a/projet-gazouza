"""Schematic format exchanged between the editor and the backend (version 2).

Owner: Damien (contract). Consumers: Noé (editor), Noémi (probes).
Specification: docs/format-schema.md. Any change goes through a dedicated PR reviewed by the
consumers.

The schematic is a graph: components have pins, and each wire says explicitly what its two ends
are attached to. Coordinates are only used for drawing; the netlist never does geometry.

Pydantic only checks the *shape* of the data here. Checks that need the whole circuit (a wire
pointing to a missing component, a duplicate id or name...) are done by the netlist module and
reported as diagnostics, not as HTTP errors.

Unknown keys in a schematic, component, junction, wire or text are ignored on purpose
(`extra="ignore"`): a file saved by a newer editor (extra display metadata) still opens.
Wire ends and diagnostic targets are the exception: they forbid extra keys, because that is how
their shapes stay mutually exclusive.
"""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

SCHEMATIC_VERSION = 2


class Point(BaseModel):
    """Position on the grid, in grid units. The y axis points down."""

    x: int
    y: int


class TextOffset(BaseModel):
    """Where a text of a component is drawn, relative to the component, in grid units.

    The offset points to the centre of the text, in the component's own frame (before the
    mirror and the rotation): a text placed by hand turns with its component and stays on the
    same side of it, while the text itself is always drawn upright. The editor snaps it to half
    a grid step.
    """

    x: float
    y: float


# --- Wire ends ------------------------------------------------------------------------------
# A wire end has exactly one of three shapes. `extra="forbid"` makes them mutually exclusive:
# an end such as {"comp": "c1", "pin": "+", "junction": "j1"} matches none of them and is
# rejected (HTTP 422).


class PinEnd(BaseModel):
    """Wire end attached to a component pin."""

    model_config = ConfigDict(extra="forbid")

    comp: str = Field(description="Component id (e.g. 'c1').")
    pin: str = Field(description="Pin name from the library (e.g. '+', '1').")


class JunctionEnd(BaseModel):
    """Wire end attached to a junction."""

    model_config = ConfigDict(extra="forbid")

    junction: str = Field(description="Junction id (e.g. 'j1').")


class FreeEnd(BaseModel):
    """Wire end attached to nothing (dangling). Produces a WIRE_DANGLING warning."""

    model_config = ConfigDict(extra="forbid")

    x: int
    y: int


WireEnd = PinEnd | JunctionEnd | FreeEnd


# --- Schematic elements ---------------------------------------------------------------------


class Component(BaseModel):
    """A placed component instance (including grounds and labels)."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(description="Stable unique id, generated by the editor (e.g. 'c1').")
    type: str = Field(description="Library id of the component (e.g. 'resistor', 'ground').")
    name: str | None = Field(
        default=None,
        description="SPICE name shown to the user (e.g. 'R1'). Absent for 'ground' and 'label'.",
    )
    position: Point
    rotation: Literal[0, 45, 90, 135, 180, 225, 270, 315] = Field(
        default=0,
        description="Clockwise, in degrees. On a diagonal (45, 135, 225, 315) each pin "
        "coordinate is rotated exactly, then rounded away from zero, so wires still attach "
        "to grid points (docs/format-schema.md, section 2).",
    )
    mirror: bool = Field(
        default=False, description="Horizontal mirror (x -> -x), applied before the rotation."
    )
    params: dict[str, str] = Field(
        default_factory=dict,
        description="Parameter values as typed by the user, SPICE suffixes allowed "
        "(e.g. {'resistance': '1k'}). For a label: {'net': 'out'}.",
    )
    name_offset: TextOffset | None = Field(
        default=None,
        description="Position of the name (or of a label's net name), set by hand. "
        "Absent: placed automatically.",
    )
    value_offset: TextOffset | None = Field(
        default=None,
        description="Position of the value, set by hand. Absent: placed automatically.",
    )


class Junction(BaseModel):
    """A point where wires meet outside a pin (a 'T')."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(description="Stable unique id (e.g. 'j1').")
    position: Point


class Text(BaseModel):
    """Free text on the schematic (title, note...). Decorative only: the netlist ignores it."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(description="Stable unique id (e.g. 't1').")
    position: Point = Field(description="Top-left corner of the text.")
    content: str = Field(max_length=2000, description="Text as typed, line breaks included.")


class Wire(BaseModel):
    """A wire between two explicit ends."""

    # `from` is a Python keyword, so the field is called `from_` in Python and `from` in JSON.
    # `serialize_by_alias` makes every dump write "from", even without `by_alias=True`
    # (e.g. when the LTspice importer saves a `.psice.json` itself).
    model_config = ConfigDict(extra="ignore", populate_by_name=True, serialize_by_alias=True)

    id: str
    from_: WireEnd = Field(alias="from")
    to: WireEnd
    points: list[Point] = Field(
        default_factory=list,
        description="Intermediate bends only, for drawing. Ignored by the netlist.",
    )


class Schematic(BaseModel):
    """Root document, saved as-is on disk (`.psice.json`)."""

    model_config = ConfigDict(extra="ignore")

    version: Literal[2] = SCHEMATIC_VERSION
    title: str | None = Field(default=None, description="Used as the netlist header.")
    components: list[Component] = Field(default_factory=list)
    junctions: list[Junction] = Field(default_factory=list)
    wires: list[Wire] = Field(default_factory=list)
    texts: list[Text] = Field(default_factory=list, description="Ignored by the netlist.")
